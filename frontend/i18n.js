/* ──────────────────────────────────────────────────────────────────────────
   SynqIO — couche bilingue FR / EN
   Traduit le DOM à la volée (site vitrine + application) à partir d'un
   dictionnaire français → anglais, et suit les rendus dynamiques via un
   MutationObserver. Les chaînes absentes du dictionnaire restent en français.
   ────────────────────────────────────────────────────────────────────────── */
(function () {
  'use strict';

  var LANG = 'fr';
  var DICT = Object.create(null);          // clé FR normalisée → valeur EN
  var LOWER = Object.create(null);         // même index, insensible à la casse
  var NUM = /\d+(?:[  .,]\d+)*/g;     // 12 · 1 500 · 19.99 → {n}
  var WORD = /[A-Za-zÀ-ÿ]{2}/;
  var ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];
  var SKIP = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, SVG: 1 };
  var ATTR_ONLY = { TEXTAREA: 1, CODE: 1, PRE: 1, IFRAME: 1, CANVAS: 1 };
  var titleFr = null, titleOut = null;

  /* ── Normalisation ─────────────────────────────────────────────────────── */
  function flat(s) { return s.replace(/\s+/g, ' ').trim(); }
  function key(s) { return flat(s).replace(NUM, '{n}'); }

  function add(map) {
    for (var k in map) {
      if (!Object.prototype.hasOwnProperty.call(map, k)) continue;
      var v = map[k];
      if (typeof v !== 'string' || !v) continue;
      var nk = key(k);
      DICT[nk] = v;
      LOWER[nk.toLowerCase()] = v;
    }
  }

  /* Réinjecte les nombres capturés à la place des jetons {n}. */
  function expand(nk, nums) {
    var en = DICT[nk];
    if (en === undefined) en = LOWER[nk.toLowerCase()];
    if (en === undefined) return null;
    if (nums && en.indexOf('{n}') !== -1) {
      var i = 0;
      en = en.replace(/\{n\}/g, function () { return i < nums.length ? nums[i++] : ''; });
    }
    return en;
  }

  /* Renvoie la traduction anglaise, ou null si la chaîne est inconnue. */
  function lookup(fr) {
    var s = flat(fr);
    if (!s || s.length > 500 || !WORD.test(s)) return null;
    var hit = expand(s.replace(NUM, '{n}'), s.match(NUM));
    if (hit !== null) return hit;
    /* « 12 produits extraits… » → compte en tête + libellé connu */
    var m = /^(\d[\d  .,]*)\s+(.+)$/.exec(s);
    if (m) {
      var inner = lookup(m[2]);
      if (inner !== null) {
        /* la casse du libellé suit celle du français d'origine */
        var head = m[2].charAt(0);
        if (head === head.toLowerCase() && head !== head.toUpperCase()) {
          inner = inner.charAt(0).toLowerCase() + inner.slice(1);
        }
        return m[1] + ' ' + inner;
      }
    }
    return null;
  }

  /* ── Application sur le DOM ────────────────────────────────────────────── */
  function tagOf(el) { return el.tagName ? String(el.tagName).toUpperCase() : ''; }

  function skipEl(el) {
    if (el.nodeType !== 1) return false;
    if (SKIP[tagOf(el)]) return true;
    return !!(el.hasAttribute && el.hasAttribute('data-noi18n'));
  }

  function textNode(n) {
    var cur = n.data;
    if (!cur || !WORD.test(cur)) return;
    var fr = (n.__i18nOut !== undefined && cur === n.__i18nOut) ? n.__i18nFr : cur;
    n.__i18nFr = fr;
    var out = fr;
    if (LANG === 'en') {
      var m = /^(\s*)([\s\S]*?)(\s*)$/.exec(fr);
      if (m[2]) {
        var t = lookup(m[2]);
        if (t !== null) out = m[1] + t + m[3];
      }
    }
    if (cur !== out) n.data = out;
    n.__i18nOut = out;
  }

  function attrNodes(el) {
    if (!el.getAttribute) return;
    var store = el.__i18nA;
    for (var i = 0; i < ATTRS.length; i++) {
      var a = ATTRS[i];
      if (!el.hasAttribute(a)) continue;
      var cur = el.getAttribute(a);
      if (!cur || !WORD.test(cur)) continue;
      if (!store) store = el.__i18nA = {};
      var prev = store[a];
      var fr = (prev && cur === prev.out) ? prev.fr : cur;
      var out = fr;
      if (LANG === 'en') {
        var t = lookup(fr);
        if (t !== null) out = t;
      }
      store[a] = { fr: fr, out: out };
      if (cur !== out) el.setAttribute(a, out);
    }
  }

  function walk(root) {
    if (!root) return;
    if (root.nodeType === 3) { textNode(root); return; }
    if (root.nodeType !== 1) return;
    if (skipEl(root)) return;
    attrNodes(root);
    if (ATTR_ONLY[tagOf(root)]) return;

    var w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT, {
      acceptNode: function (n) {
        if (n.nodeType === 1) {
          if (skipEl(n)) return NodeFilter.FILTER_REJECT;
          if (ATTR_ONLY[tagOf(n)]) { attrNodes(n); return NodeFilter.FILTER_REJECT; }
          return NodeFilter.FILTER_ACCEPT;
        }
        return NodeFilter.FILTER_ACCEPT;
      }
    });
    var n;
    while ((n = w.nextNode())) {
      if (n.nodeType === 1) attrNodes(n); else textNode(n);
    }
  }

  function applyTitle() {
    if (titleFr === null || document.title !== titleOut) titleFr = document.title;
    var out = titleFr;
    if (LANG === 'en') {
      var t = lookup(titleFr);
      if (t !== null) out = t;
    }
    if (document.title !== out) document.title = out;
    titleOut = out;
  }

  /* ── Suivi des rendus dynamiques ───────────────────────────────────────── */
  var observer = null;
  function observe() {
    if (observer || typeof MutationObserver === 'undefined') return;
    observer = new MutationObserver(function (recs) {
      for (var i = 0; i < recs.length; i++) {
        var r = recs[i];
        if (r.type === 'childList') {
          for (var j = 0; j < r.addedNodes.length; j++) walk(r.addedNodes[j]);
        } else if (r.type === 'characterData') {
          if (r.target.parentNode && !skipEl(r.target.parentNode)) textNode(r.target);
        } else if (r.type === 'attributes') {
          if (!skipEl(r.target)) attrNodes(r.target);
        }
      }
    });
    observer.observe(document.documentElement, {
      subtree: true, childList: true, characterData: true,
      attributes: true, attributeFilter: ATTRS
    });
  }

  /* ── Sélecteur de langue ───────────────────────────────────────────────── */
  var CSS = '.sq-lang{display:inline-flex;align-items:center;gap:2px;padding:2px;border-radius:9999px;' +
    'border:1px solid rgba(124,58,237,.18);background:rgba(255,255,255,.92);flex-shrink:0}' +
    '.sq-lang button{appearance:none;border:0;background:transparent;cursor:pointer;padding:5px 10px;' +
    "border-radius:9999px;font-family:'Inter',sans-serif;font-size:11px;font-weight:700;letter-spacing:.05em;" +
    'color:#6b7280;line-height:1;transition:all .18s}' +
    '.sq-lang button:hover{color:#4c1d95}' +
    '.sq-lang button[aria-pressed="true"]{background:linear-gradient(135deg,#7c3aed,#4f46e5);color:#fff;' +
    'box-shadow:0 2px 8px rgba(124,58,237,.35)}' +
    '.sq-lang.on-dark{border-color:rgba(255,255,255,.14);background:rgba(255,255,255,.06)}' +
    '.sq-lang.on-dark button{color:rgba(255,255,255,.62)}' +
    '.sq-lang.on-dark button:hover{color:#fff}';

  function injectCss() {
    if (document.getElementById('sq-lang-css')) return;
    var s = document.createElement('style');
    s.id = 'sq-lang-css';
    s.textContent = CSS;
    (document.head || document.documentElement).appendChild(s);
  }

  function mountSwitches() {
    var hosts = document.querySelectorAll('[data-lang-switch]');
    for (var i = 0; i < hosts.length; i++) {
      var h = hosts[i];
      if (h.__sqLang) continue;
      h.__sqLang = true;
      h.setAttribute('data-noi18n', '');
      h.classList.add('sq-lang');
      if (h.getAttribute('data-lang-switch') === 'dark') h.classList.add('on-dark');
      h.innerHTML = '<button type="button" data-l="fr">FR</button><button type="button" data-l="en">EN</button>';
      h.addEventListener('click', function (e) {
        var b = e.target.closest('button[data-l]');
        if (b) { e.preventDefault(); setLang(b.getAttribute('data-l')); }
      });
    }
    syncSwitches();
  }

  function syncSwitches() {
    var btns = document.querySelectorAll('.sq-lang button[data-l]');
    for (var i = 0; i < btns.length; i++) {
      btns[i].setAttribute('aria-pressed', btns[i].getAttribute('data-l') === LANG ? 'true' : 'false');
    }
  }

  /* ── API publique ──────────────────────────────────────────────────────── */
  function setLang(l) {
    LANG = (l === 'en') ? 'en' : 'fr';
    try { localStorage.setItem('synqio_lang', LANG); } catch (e) { /* privé */ }
    document.documentElement.lang = LANG;
    if (document.body) walk(document.body);
    applyTitle();
    syncSwitches();
    try {
      document.dispatchEvent(new CustomEvent('synqio:lang', { detail: LANG }));
    } catch (e) { /* vieux navigateur */ }
  }

  function detect() {
    var stored = null;
    try { stored = localStorage.getItem('synqio_lang'); } catch (e) { /* privé */ }
    if (stored === 'fr' || stored === 'en') return stored;
    var nav = (navigator.language || navigator.userLanguage || 'fr').toLowerCase();
    return nav.indexOf('fr') === 0 ? 'fr' : 'en';
  }

  function boot() {
    injectCss();
    mountSwitches();
    LANG = detect();
    document.documentElement.lang = LANG;
    if (LANG === 'en' && document.body) { walk(document.body); applyTitle(); }
    syncSwitches();
    observe();
  }

  window.SQI18N = {
    add: add,
    set: setLang,
    get: function () { return LANG; },
    t: function (fr) { return LANG === 'en' ? (lookup(fr) || fr) : fr; },
    refresh: function () { if (document.body) walk(document.body); },
    boot: function () {
      if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', boot);
      else boot();
    }
  };
})();

